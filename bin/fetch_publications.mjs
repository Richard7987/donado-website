#!/usr/bin/env node
// Rebuild _bibliography/papers.bib from ORCID + Crossref. Needs Node 18+.
//
//   node bin/fetch_publications.mjs             all works with a DOI
//   node bin/fetch_publications.mjs --limit 8   8 most recent
//   node bin/fetch_publications.mjs --dry-run   print, don't write
//
// DOI-less entries go in _bibliography/manual.bib and are appended unchanged.

const ORCID = "0000-0002-7032-3265";
const UA = "donado-website/1.0 (mailto:fernando@uaeh.edu.mx)";

// Cite keys (see makeKey) shown on the home page.
const SELECTED = new Set(["PalaciosRazo2026dynamics", "SolanoCabrera2025self"]);

// Full journal name -> _data/venues.yml key, for al-folio's `abbr` badge.
const ABBR = {
  "Physical Review E": "PRE",
  "Physical Review Letters": "PRL",
  "Physica A: Statistical Mechanics and its Applications": "Physica A",
  "Scientific Reports": "Sci. Rep.",
  "Soft Matter": "Soft Matter",
  "Physica Scripta": "Phys. Scr.",
  "Annual Review of Condensed Matter Physics": "Annu. Rev. CMP",
  "The European Physical Journal E": "EPJE",
  "Granular Matter": "Granular Matter",
};

const args = process.argv.slice(2);
const limitIdx = args.indexOf("--limit");
const LIMIT = limitIdx >= 0 ? parseInt(args[limitIdx + 1], 10) : 0;
const DRY = args.includes("--dry-run");

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function orcidWorks() {
  const res = await fetch(`https://pub.orcid.org/v3.0/${ORCID}/works`, {
    headers: { Accept: "application/json", "User-Agent": UA },
  });
  if (!res.ok) throw new Error(`ORCID ${res.status}`);
  const data = await res.json();
  const rows = [];
  for (const g of data.group) {
    const s = g["work-summary"][0];
    const ids = g["external-ids"]?.["external-id"] || [];
    const doi = ids.find((e) => e["external-id-type"] === "doi");
    if (!doi) continue;
    rows.push({
      year: parseInt(s["publication-date"]?.year?.value || "0", 10),
      doi: doi["external-id-value"].trim().toLowerCase(),
    });
  }
  const seen = new Set();
  return rows
    .filter((r) => (seen.has(r.doi) ? false : seen.add(r.doi)))
    .sort((a, b) => b.year - a.year);
}

async function bibtexFor(doi) {
  const res = await fetch(`https://doi.org/${doi}`, {
    headers: { Accept: "application/x-bibtex", "User-Agent": UA },
    redirect: "follow",
  });
  if (!res.ok) throw new Error(`Crossref ${res.status} for ${doi}`);
  return (await res.text()).trim();
}

function fieldOf(bib, name) {
  const m = bib.match(new RegExp(`${name}\\s*=\\s*[{"]([^}"]+)[}"]`, "i"));
  return m ? m[1].trim() : "";
}

const strip = (s) =>
  s
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^A-Za-z0-9]/g, "");

// Crossref keys collide (three "Escobar_2025"); jekyll-scholar needs unique ones.
function makeKey(bib) {
  const last = strip(
    (fieldOf(bib, "author").split(" and ")[0] || "Anon").split(",")[0],
  );
  const year = fieldOf(bib, "year") || "0000";
  const word = (fieldOf(bib, "title").match(/[A-Za-z]{4,}/) || [
    "paper",
  ])[0].toLowerCase();
  return `${last}${year}${word}`;
}

function decorate(bib, usedKeys) {
  let key = makeKey(bib);
  while (usedKeys.has(key)) key += "x";
  usedKeys.add(key);
  bib = bib.replace(/^(@\w+\{)\s*[^,]+,/, `$1${key},`);

  const journal = fieldOf(bib, "journal");
  const extra = [];
  if (ABBR[journal]) extra.push(`  abbr={${ABBR[journal]}}`);
  if (SELECTED.has(key)) extra.push(`  selected={true}`);
  if (!extra.length) return bib;
  return bib.replace(/^(@\w+\{[^,]+,)/, `$1\n${extra.join(",\n")},`);
}

async function main() {
  const works = await orcidWorks();
  const pick = LIMIT > 0 ? works.slice(0, LIMIT) : works;
  console.error(`ORCID: ${works.length} DOIs, taking ${pick.length}`);

  const out = [
    "% Generated by bin/fetch_publications.mjs from ORCID + Crossref.",
    "% Overwritten on every run; hand-maintained entries live in manual.bib.",
    "",
  ];

  const usedKeys = new Set();
  for (const w of pick) {
    try {
      out.push(decorate(await bibtexFor(w.doi), usedKeys), "");
      console.error(`  ok  ${w.year}  ${w.doi}`);
    } catch (e) {
      console.error(`  FAIL ${w.doi}: ${e.message}`);
    }
    await sleep(1100);
  }

  const { writeFileSync, readFileSync, existsSync } = await import("node:fs");
  const manualPath = new URL("../_bibliography/manual.bib", import.meta.url);
  let manualCount = 0;
  if (existsSync(manualPath)) {
    const manual = readFileSync(manualPath, "utf8");
    manualCount = (manual.match(/^@/gm) || []).length;
    out.push("% appended from _bibliography/manual.bib", "", manual.trim(), "");
  }

  const text = out.join("\n") + "\n";
  if (DRY) {
    process.stdout.write(text);
    return;
  }
  writeFileSync(new URL("../_bibliography/papers.bib", import.meta.url), text);
  console.error(`\nwrote papers.bib (${pick.length} from ORCID + ${manualCount} manual)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
